import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {build} from 'esbuild';
const bundle=await build({entryPoints:['browser/history-labels.js'],bundle:true,write:false,format:'esm'});
const {describeSpan,spanStatus,interfaceLabels}=await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const s={component:'authorization-http',operation:'attempt',outcome:'RETURNED',links:{method:'GET',route:'/api/v1/sessions/current',httpStatus:'200'}};
assert.equal(describeSpan(s)[0],'核验当前银行登录身份');
assert.equal(spanStatus(s),'来源接口已返回 HTTP 200，不单独代表银行业务完成');
assert(!spanStatus(s).includes('授权通过'));
assert.equal(describeSpan({...s,links:{method:'POST',route:'/api/v1/sessions/current'}})[0],'调用来源系统接口');
assert.equal(describeSpan({...s,links:{method:'GET',route:'/new-route'}})[0],'调用来源系统接口');
assert.equal(describeSpan({component:'host',operation:'native-lock-wait'})[0],'等待当前 Agent 空闲');
assert.equal(spanStatus({...s,links:{businessStatus:'FAILED'}}),'业务失败');
assert.equal(describeSpan({component:'model'})[1],'SDK 调用区间；模型 HTTP 是否发出未观测');
const tool={component:'runtime-tool',spanId:'t'};
assert.equal(describeSpan(tool,[{component:'capability',parentSpanId:'t',links:{capabilityId:'account.balance.query'}}])[0],'执行工具：查询账户余额');
assert.equal(describeSpan(tool,[{component:'capability',parentSpanId:'other',links:{capabilityId:'account.balance.query'}}])[0],'执行金融工具');
for(const key of Object.keys(interfaceLabels)) assert.match(key,/^(GET|POST) \/api\/v1\//);
assert(readFileSync('examples/local-workbench/icons.svg','utf8').includes('id="clock-3"'));
assert(readFileSync('browser/workbench.js','utf8').includes('["history", "clock-3", "运行记录"]'));
console.log('history labels: exact route/method, parent links, unknown fallback, result semantics and icon passed');
