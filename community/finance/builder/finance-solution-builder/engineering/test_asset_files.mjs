import assert from 'node:assert/strict';
import {fileKey,nodeFileKeys,resolveFile,fileSource} from '../browser/asset-files.js';
import {versionOf} from '../browser/asset-graph.js';
const one={fileId:'asset-file:one',path:'SKILL.md',content:'first',reference:{id:'first',version:'1',source:'repo://one'}};
const two={fileId:'asset-file:two',path:'SKILL.md',content:'second',reference:{id:'second',version:'2',source:'repo://two'}};
assert.equal(resolveFile({files:[one,two]},one.fileId),one);
assert.equal(resolveFile({files:[one,two]},two.fileId),two);
assert.throws(()=>resolveFile({files:[one,two]},'SKILL.md'),/多个来源/);
assert.equal(resolveFile({files:[one]},'SKILL.md'),one);
assert.equal(resolveFile({files:[one]},'missing'),null);
assert.equal(fileKey({path:'legacy'}),'legacy');
assert.deepEqual(nodeFileKeys({files:['SKILL.md'],fileIds:[one.fileId]}),[one.fileId]);
assert.deepEqual(nodeFileKeys({files:['legacy']}),['legacy']);
assert.equal(fileSource({}),'来源待核对');
assert.equal(fileSource(two),'second · v2 · repo://two');
assert.equal(versionOf({files:['SKILL.md'],fileIds:[two.fileId]},{files:[one,two]}),'v2');
assert.equal(versionOf({files:['SKILL.md']},{files:[one,two]}),'来源有歧义，请核对引用');
assert.equal(versionOf({fileIds:[one.fileId,two.fileId]},{files:[one,two]}),'多个版本，见具体引用');
assert.equal(versionOf({reference:{version:'3'},fileIds:[two.fileId]},{files:[one,two]}),'v3');
console.log('14 source-aware file checks passed');
