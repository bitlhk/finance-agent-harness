"""Deterministic OpenCode protocol double; it never starts a model or network service."""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Any


def vendor_event(event_type: str, session_id: str = "session-1", **properties: Any) -> dict[str, Any]:
    return {
        "type": event_type,
        "properties": {"sessionID": session_id, **properties},
    }


def successful_batches(*, approval: bool = False) -> list[list[Mapping[str, Any]]]:
    head: list[Mapping[str, Any]] = [
        vendor_event("message.updated", info={"sessionID": "session-1", "cost": 0.0001}),
        vendor_event("message.part.updated", part={"type": "step-start"}),
        vendor_event(
            "message.part.updated",
            part={"type": "tool", "state": {"status": "completed"}},
        ),
    ]
    if approval:
        head.append(
            vendor_event("permission.asked", id="vendor-permission-1", permission="bash")
        )
        return [head, [vendor_event("session.idle")]]
    head.append(vendor_event("session.idle"))
    return [head]


class ScriptedOpenCodeRuntime:
    """In-memory protocol implementation with observable side effects."""

    def __init__(
        self,
        workspace: Path,
        *,
        batches: list[list[Mapping[str, Any]]] | None = None,
        diff_paths: tuple[str, ...] = ("candidate/src/generated.py",),
        health: Mapping[str, Any] | None = None,
        fail_start: bool = False,
        write_changes: bool = True,
    ) -> None:
        self.workspace = workspace
        self.batches = list(batches or successful_batches())
        self.diff_paths = diff_paths
        self.health_payload = dict(health or {"healthy": True, "version": "1.18.29"})
        self.fail_start = fail_start
        self.write_changes = write_changes
        self.started = False
        self.stopped = False
        self.aborted = False
        self.session_id = "session-1"
        self.prompts: list[str] = []
        self.permission_replies: list[tuple[str, str]] = []

    def start(self) -> None:
        if self.fail_start:
            raise RuntimeError("fixture startup failure")
        self.started = True

    def health(self) -> Mapping[str, Any]:
        return self.health_payload

    def configuration(self) -> Mapping[str, Any]:
        edit: dict[str, str] = {"*": "deny"}
        for relative in ("candidate/src", "candidate/tests"):
            edit[relative] = "allow"
            edit[f"{relative}/**"] = "allow"
        return {
            "share": "disabled",
            "autoupdate": False,
            "permission": {
                "*": "ask",
                "read": {
                    "*": "allow",
                    "*.env": "deny",
                    "*.env.*": "deny",
                    "*.env.example": "allow",
                },
                "edit": edit,
                "bash": "ask",
                "external_directory": "deny",
                "webfetch": "deny",
                "websearch": "deny",
                "task": "deny",
                "skill": "deny",
                "question": "deny",
                "doom_loop": "ask",
            },
        }

    def create_session(self, title: str) -> str:
        assert title
        return self.session_id

    def submit_prompt(self, session_id: str, prompt: str, model: str | None) -> None:
        assert session_id == self.session_id
        self.prompts.append(prompt)
        if self.write_changes:
            for relative in self.diff_paths:
                target = self.workspace / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text("# generated by deterministic protocol double\n", encoding="utf-8")

    def stream_events(self, session_id: str) -> Iterable[Mapping[str, Any]]:
        assert session_id == self.session_id
        return iter(self.batches.pop(0) if self.batches else [])

    def diff(self, session_id: str) -> tuple[Mapping[str, Any], ...]:
        assert session_id == self.session_id
        return tuple({"file": item} for item in self.diff_paths)

    def reply_permission(self, session_id: str, permission_id: str, response: str) -> None:
        assert session_id == self.session_id
        self.permission_replies.append((permission_id, response))

    def abort(self, session_id: str) -> None:
        assert session_id == self.session_id
        self.aborted = True

    def session_exists(self, session_id: str) -> bool:
        return session_id == self.session_id and self.started and not self.stopped

    def alive(self) -> bool:
        return self.started and not self.stopped

    def stop(self) -> None:
        self.stopped = True
